/// Checks whether a given endpoint is internal.
pub fn is_endpoint_internal(endpoint: &Endpoint) -> bool {
    let ExecutionTarget::Http(http_target) = endpoint.execution_target() else {
        return true;
    };

    let Some(_) = http_target
        .execution_pipeline()
        .to_owned()
        .map(|execution_step| {
            execution_step
                .executor()
                .to_owned()
                .into_arc_any()
                .downcast::<MySQLExecutor>()
                .ok()
                .is_some()
                || execution_step
                    .executor()
                    .to_owned()
                    .into_arc_any()
                    .downcast::<MySQLExecutorProxy>()
                    .ok()
                    .is_some()
        })
    else {
        // It's trivial that if the endpoint doesn't have a MySQL executor it's because it's internal.
        return true;
    };

    if let Some(_) = APP_INTERNAL_ENDPOINTS
        .inner()
        .iter()
        .find(|_endpoint| *_endpoint.id() == endpoint.id())
    {
        return true;
    }

    return false;
}
